// RemoteFM1FW README.md: a generated firmware table (from the manifests of the files to release) and generated
// FM1VST build provenance, each between markers so the hand-written prose around them stays the owner's.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { cfg, run } from "./util.js";
import { parseReadmeTable, ghSlug } from "./catalog.js";

const T0 = "<!-- rfm1-table:start (generated by RFM1Manager: edit the manifests or the licence notes, then Refresh) -->";
const T1 = "<!-- rfm1-table:end -->";
const B0 = "<!-- rfm1-build:start (generated by RFM1Manager from each file's built_by) -->";
const B1 = "<!-- rfm1-build:end -->";

export const readmePath = () => join(cfg.fwRepo, "README.md");
export const readReadme = () => (existsSync(readmePath()) ? readFileSync(readmePath(), "utf8") : "");

// files: [{ file, manifest, hostedDespiteGate }]
export async function generateTable(files, oldMd) {
  const old = parseReadmeTable(oldMd || "");
  const rows = ["| File | Firmware | Author | Licence | Source (the commit built) |", "| --- | --- | --- | --- | --- |"];
  for (const f of [...files].sort((a, b) => a.file.localeCompare(b.file))) {
    const m = f.manifest;
    const prev = old[m.id];
    // keep a hand-written licence note ("GPL-3.0-only (+ the Hügelton icons, all rights reserved)") if it starts with the SPDX id
    const lic = prev && prev.license.startsWith(m.license) ? prev.license : m.license;
    let fw = `${m.name} ${m.version}`;
    if (prev && prev.firmware.startsWith(m.name) && prev.firmware.replace(/ †$/, "") !== fw) {
      const extra = prev.firmware.replace(/ †$/, "").slice(m.name.length).replace(/^\s*[^,\s]+/, "");
      if (extra && !/^\s*\d/.test(extra)) fw += extra; // e.g. "DUELL (unofficial build) 1.0, with ..." keeps its tail
    }
    if (f.hostedDespiteGate || prev?.hosted) fw += " †";
    const author = prev && prev.author.startsWith((m.authors || [])[0] || "\u0000") ? prev.author : (m.authors || []).join(", ");
    const [repoUrl, commit] = (m.source_url || "").split("@");
    const slug = ghSlug(repoUrl) || repoUrl;
    rows.push(`| \`${f.file}\` | ${fw} | ${author} | ${lic} | [${slug}](${repoUrl}/tree/${commit}) |`);
  }
  return rows.join("\n");
}

export async function generateBuildNotes(files) {
  const groups = new Map();
  for (const f of files) {
    const b = /FM1VST (\S+) \(([0-9a-f]+)\).*emcc (\S+)/.exec(f.manifest.built_by || "");
    const key = b ? b[2] : "unknown";
    if (!groups.has(key)) groups.set(key, { ver: b?.[1], emcc: b?.[3], files: [] });
    groups.get(key).files.push(f.file);
  }
  const lines = ["**Build provenance** (each file's `built_by`):", ""];
  for (const [c, g] of groups) {
    let full = c, branch = "";
    const r = await run("git", ["-C", cfg.fm1vst, "rev-parse", "--verify", "-q", `${c}^{commit}`]);
    if (r.code === 0) {
      full = r.out.trim();
      const br = await run("git", ["-C", cfg.fm1vst, "for-each-ref", "--points-at", full, "--format=%(refname:short)", "refs/heads"]);
      branch = br.out.trim().split("\n").filter(Boolean).sort((a, b) => (a.startsWith(cfg.branch) ? 1 : 0) - (b.startsWith(cfg.branch) ? 1 : 0))[0] || "";
    }
    lines.push(`- FM1VST ${g.ver || "?"}${branch ? `, branch \`${branch}\`` : ""}, commit [\`${c.slice(0, 7)}\`](https://github.com/${cfg.fm1vstGh}/tree/${full}), Emscripten ${g.emcc || "?"}: ${g.files.sort().map((x) => `\`${x}\``).join(", ")}`);
  }
  return lines.join("\n");
}

function replaceBlock(md, a, b, body, fallbackRe) {
  const i = md.indexOf(a), j = md.indexOf(b);
  if (i >= 0 && j > i) return md.slice(0, i) + `${a}\n${body}\n${b}` + md.slice(j + b.length);
  if (fallbackRe) {
    const m = fallbackRe.exec(md);
    if (m) return md.slice(0, m.index) + `${a}\n${body}\n${b}\n` + md.slice(m.index + m[0].length);
  }
  return null;
}

export async function refreshReadme(md, files) {
  const table = await generateTable(files, md);
  const notes = await generateBuildNotes(files);
  let out = replaceBlock(md, T0, T1, table, /^\| File \|.*\n(?:\|.*\n?)*/m);
  if (out === null) out = md + `\n\n${T0}\n${table}\n${T1}\n`;
  const withNotes = replaceBlock(out, B0, B1, notes, null);
  out = withNotes !== null ? withNotes : out.replace(T1, `${T1}\n\n${B0}\n${notes}\n${B1}`);
  return out;
}

export function saveReadme(md) { writeFileSync(readmePath(), md); }
